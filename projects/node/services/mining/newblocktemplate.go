// NewBlockTemplate returns a new block template that is ready to be solved
// using the transactions from the passed transaction source pool and a coinbase
// that either pays to the passed address if it is not nil, or a coinbase that
// is redeemable by anyone if the passed address is nil.  The nil address
// functionality is useful since there are cases such as the getblocktemplate
// RPC where external mining software is responsible for creating their own
// coinbase which will replace the one generated for the block template.  Thus
// the need to have configured address can be avoided.
//
// The transactions selected and included are prioritized according to several
// factors.  First, each transaction has a priority calculated based on its
// value, age of inputs, and size.  Transactions which consist of larger
// amounts, older inputs, and small sizes have the highest priority.  Second, a
// fee per kilobyte is calculated for each transaction.  Transactions with a
// higher fee per kilobyte are preferred.  Finally, the block generation related
// policy settings are all taken into account.
//
// Transactions which only spend outputs from other transactions already in the
// block chain are immediately added to a priority queue which either
// prioritizes based on the priority (then fee per kilobyte) or the fee per
// kilobyte (then priority) depending on whether or not the BlockPrioritySize
// policy setting allots space for high-priority transactions.  Transactions
// which spend outputs from other transactions in the source pool are added to a
// dependency map so they can be added to the priority queue once the
// transactions they depend on have been included.
//
// Once the high-priority area (if configured) has been filled with
// transactions, or the priority falls below what is considered high-priority,
// the priority queue is updated to prioritize by fees per kilobyte (then
// priority).
//
// When the fees per kilobyte drop below the TxMinFreeFee policy setting, the
// transaction will be skipped unless the BlockMinSize policy setting is
// nonzero, in which case the block will be filled with the low-fee/free
// transactions until the block size reaches that minimum size.
//
// Any transactions which would cause the block to exceed the BlockMaxSize
// policy setting, exceed the maximum allowed signature operations per block, or
// otherwise cause the block to be invalid are skipped.
//
// Given the above, a block generated by this function is of the following form:
//
//   -----------------------------------  --  --
//  |      Coinbase Transaction         |   |   |
//  |-----------------------------------|   |   |
//  |                                   |   |   | ----- policy.BlockPrioritySize
//  |   High-priority Transactions      |   |   |
//  |                                   |   |   |
//  |-----------------------------------|   | --
//  |                                   |   |
//  |                                   |   |
//  |                                   |   |--- (policy.BlockMaxSize) / 2
//  |  Transactions prioritized by fee  |   |
//  |  until <= policy.TxMinFreeFee     |   |
//  |                                   |   |
//  |                                   |   |
//  |                                   |   |
//  |-----------------------------------|   |
//  |  Low-fee/Non high-priority (free) |   |
//  |  transactions (while block size   |   |
//  |  <= policy.BlockMinSize)          |   |
//   -----------------------------------  --
//
//  This function returns nil, nil if there are not enough voters on any of
//  the current top blocks to create a new block template.

func NewBlockTemplate(
	policy *Policy, params *params.Params,
	sigCache *txscript.SigCache, tpool *legacypool.LegacyPool,
	timeSource model.MedianTimeSource, consensus model.Consensus,
	payToAddress ethcommon.Address, parents []*common.Hash,
	powType pow.PowType, coinbaseFlags CoinbaseFlags,
) (*types.BlockTemplate, error) {
	return newBlockTemplate(policy, params, sigCache, tpool, timeSource, consensus, payToAddress, parents, powType, coinbaseFlags, true)
}

// NewBlockTemplateWithoutPendingTransactions builds a valid mining template
// without EVM pending transactions. It is a recovery path for stale pending
// snapshots; normal template builds should use NewBlockTemplate.
func NewBlockTemplateWithoutPendingTransactions(
	policy *Policy, params *params.Params,
	sigCache *txscript.SigCache, tpool *legacypool.LegacyPool,
	timeSource model.MedianTimeSource, consensus model.Consensus,
	payToAddress ethcommon.Address, parents []*common.Hash,
	powType pow.PowType, coinbaseFlags CoinbaseFlags,
) (*types.BlockTemplate, error) {
	return newBlockTemplate(policy, params, sigCache, tpool, timeSource, consensus, payToAddress, parents, powType, coinbaseFlags, false)
}

func newBlockTemplate(
	policy *Policy, params *params.Params,
	sigCache *txscript.SigCache, tpool *legacypool.LegacyPool,
	timeSource model.MedianTimeSource, consensus model.Consensus,
	payToAddress ethcommon.Address, parents []*common.Hash,
	powType pow.PowType, coinbaseFlags CoinbaseFlags,
	includePendingTransactions bool,
) (*types.BlockTemplate, error) {
	buildStart := time.Now()
	defer templateBuildTotalDuration.UpdateSince(buildStart)

	bc := consensus.BlockChain().(*blockchain.BlockChain)
	bd := bc.Blockdag()
	bp := bc.EVMChain().BdagPool()
	subsidyCache := bc.FetchSubsidyCache()

	// 2) Determine next height & baseFee
	mainp := bd.GetMainChainTip()
	if parents != nil {
		mainp, parents = bd.GetMainParentAndList(parents)
	}
	nextHeight := uint64(mainp.GetHeight() + 1)
	blues := int64(bd.GetBluesByBlock(mainp))

	// Init Root from EVM State (which includes txs)
	// We need to apply Finalize to get the consensus rewards into the state
	pendingStart := time.Now()
	evmBlock, _, _ := bp.Pending()
	templateBuildPendingDuration.UpdateSince(pendingStart)
	if evmBlock == nil {
		return nil, fmt.Errorf("no block template available")
	}

	// compute your DAG-header overhead + parent-merkle overhead once
	const headerOverhead = blockHeaderOverhead
	expectParents := parents
	if expectParents == nil {
		expectParents = bc.GetMiningTips(blockdag.MaxPriority)
	}
	parentBytes := uint32(s.VarIntSerializeSize(uint64(len(expectParents))))
	parentBytes += uint32(len(expectParents)) * common.HashLength

	// now enforce both gas & DAG-size limits on the EVM tx list
	var allTxs []*ethtypes.Transaction
	if includePendingTransactions {
		allTxs = evmBlock.Transactions()
	}
	finalTxs := make([]*ethtypes.Transaction, 0, len(allTxs))
	fees := make([]int64, 1, len(allTxs)+1)
	usedSize := uint32(headerOverhead) + parentBytes
	maxSize := policy.BlockMaxSize
	totalFees := int64(0)

	for _, tx := range allTxs {
		sz := uint32(tx.Size())

		// DAG byte‐size check
		if usedSize+sz > maxSize {
			break
		}

		finalTxs = append(finalTxs, tx)
		usedSize += sz
		fee := tx.GasPrice().Int64() * int64(tx.Gas())
		totalFees += fee
		fees = append(fees, fee)
	}

	// now finalTxs is your fully validated, capacity-bounded list
	// continue with computing merkle roots, state root, header, etc.

	// Build Merkle roots, header & state root
	merkleStart := time.Now()
	merkles := merkle.BuildMerkleTreeStoreForEVM(finalTxs, false)
	paMerkles := merkle.BuildParentsMerkleTreeStore(expectParents)
	templateBuildMerkleDuration.UpdateSince(merkleStart)

	ts := MedianAdjustedTime(bc, timeSource)
	diff, _ := bc.CalcNextRequiredDifficulty(ts, powType)
	ver, _ := bc.CalcNextBlockVersion()
	reward := blockchain.CalcBlockWorkSubsidy(subsidyCache, bd.GetBlueInfo(mainp), params, ts.Unix())

	header := types.BlockHeader{
		Version:         ver,
		ParentRoot:      *paMerkles[len(paMerkles)-1],
		TxRoot:          *merkles[len(merkles)-1],
		Timestamp:       ts,
		Difficulty:      diff,
		Pow:             pow.GetInstance(powType, 0, 0, nil),
		CoinbaseAddress: payToAddress,
		BlockHeight:     nextHeight,
		Reward:          reward,
	}

	// Calculate state root (BDAG specific). CalculateStateRoot zeroes the
	// header state-root field before hashing, so only the fully assembled
	// parent/transaction view needs to be hashed here.
	stateRootStart := time.Now()
	trial := types.Block{Header: header}
	for _, p := range expectParents {
		_ = trial.AddParent(p)
	}
	for _, tx := range finalTxs {
		_ = trial.AddTransaction(tx)
	}
	header.StateRoot = *bc.CalculateStateRoot(&trial)
	templateBuildStateRootDuration.UpdateSince(stateRootStart)

	// assemble the real block
	blk := types.Block{Header: header}
	for _, p := range expectParents {
		_ = blk.AddParent(p)
	}
	for _, tx := range finalTxs {
		_ = blk.AddTransaction(tx)
	}
	sblock := types.NewBlock(&blk)

	// 5) Validate against DAG + P2P rules
	checkStart := time.Now()
	newNode := blockchain.NewBlockNode(sblock)
	vir := bd.CreateVirtualBlock(newNode)
	if vir == nil {
		templateBuildCheckConnectDuration.UpdateSince(checkStart)
		return nil, fmt.Errorf("unable to create virtual block")
	}
	if committed, committedRoot, err := bc.PrepareEVMStateCommitmentForTemplate(&blk, uint64(vir.GetHeight())); err != nil {
		templateBuildCheckConnectDuration.UpdateSince(checkStart)
		return nil, err
	} else if committed {
		blk.Header.StateRoot = *committedRoot
		sblock = types.NewBlock(&blk)
	}
	if err := bc.CheckConnectBlockTemplate(sblock, uint64(vir.GetHeight())); err != nil {
		templateBuildCheckConnectDuration.UpdateSince(checkStart)
		return nil, err
	}
	templateBuildCheckConnectDuration.UpdateSince(checkStart)

	// 6) Mark the negative coinbase offset and return.
	fees[0] = -totalFees

	return &types.BlockTemplate{
		Block:           &blk,
		SerializedBlock: sblock,
		Fees:            fees,
		Height:          nextHeight,
		Blues:           int64(blues),
		ValidPayAddress: payToAddress != (ethcommon.Address{}),
		Difficulty:      diff,
		BlockFees:       totalFees,
		TxMerklePath:    merkle.GetMerkleTreePath(merkles, len(finalTxs)),
	}, nil
}

// UpdateBlockTime updates the timestamp in the header of the passed block to
// the current time while taking into account the median time of the last
// several blocks to ensure the new time is after that time per the chain
// consensus rules.  Finally, it will update the target difficulty if needed
// based on the new time for the test networks since their target difficulty can
// change based upon time.
func UpdateBlockTime(msgBlock *types.Block, chain *blockchain.BlockChain, timeSource model.MedianTimeSource,
	activeNetParams *params.Params) error {

	// The new timestamp is potentially adjusted to ensure it comes after
	// the median time of the last several blocks per the chain consensus
	// rules.
	newTimestamp := MedianAdjustedTime(chain, timeSource)
	msgBlock.Header.Timestamp = newTimestamp

	// If running on a network that requires recalculating the difficulty,
	// do so now.
	if activeNetParams.ReduceMinDifficulty {
		difficulty, err := chain.CalcNextRequiredDifficulty(
			newTimestamp, msgBlock.Header.Pow.GetPowType())
		if err != nil {
			return miningRuleError(ErrGettingDifficulty, err.Error())
		}
		msgBlock.Header.Difficulty = difficulty
	}

	return nil
}
