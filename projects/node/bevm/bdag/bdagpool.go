func (m *BdagPool) resetTemplateWithGeneration(allowWhileSyncing bool, syncGeneration uint64, guardSyncState bool) error {
	log.Debug("Try to reset bdag pool")
	if !m.isRunning() || m.resetTemplate == nil || m.quit == nil {
		return wrapPendingTemplateResetError(errBdagPoolStopped)
	}
	msg := &resetTemplateMsg{
		reply:             make(chan error, 1),
		allowWhileSyncing: allowWhileSyncing,
		syncGeneration:    syncGeneration,
		guardSyncState:    guardSyncState,
	}
	select {
	case m.resetTemplate <- msg:
	case <-m.quit:
		return wrapPendingTemplateResetError(errBdagPoolStopped)
	}
	select {
	case err := <-msg.reply:
		return wrapPendingTemplateResetError(err)
	case <-m.quit:
		return wrapPendingTemplateResetError(errBdagPoolStopped)
	}
}

