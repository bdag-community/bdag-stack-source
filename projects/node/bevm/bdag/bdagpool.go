// ResetTemplateForMining is used by the miner after its own mining readiness
// preflight has already decided that template generation is safe. The BdagPool
// syncing guard still applies here so a sync transition between the preflight
// and reset request fails closed.
func (m *BdagPool) ResetTemplateForMining() error {
	return m.resetTemplateWithOptions(false)
}

// ResetTemplateForCanonicalMining is the narrow downloader-latch bypass used
// after the miner has authenticated fresh peer consensus. Recheck the exact
// committed native/EVM tuple here and again in updateTemplate so a concurrent
// state transition fails closed.
func (m *BdagPool) ResetTemplateForCanonicalMining() error {
	if m == nil {
		return wrapPendingTemplateResetError(errBdagPoolSyncing)
	}
	syncGeneration := m.syncing.Snapshot()
	if !m.CanonicalMiningTemplateReady() {
		return wrapPendingTemplateResetError(errBdagPoolSyncing)
	}
	if err := m.resetTemplateWithGeneration(true, syncGeneration, true); err != nil {
		return err
	}
	return nil
}

