// downloaderLatch tracks downloader observations independently from the
// current syncing value. A generation change prevents a canonical template
// reset from recycling a latch after a newer downloader event was observed.
// The zero value is ready for use.
type downloaderLatch struct {
	mu         sync.Mutex
	syncing    bool
	generation uint64
}

func (l *downloaderLatch) Load() bool {
	if l == nil {
		return false
	}
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.syncing
}

func (l *downloaderLatch) Store(syncing bool) {
	if l == nil {
		return
	}
	l.mu.Lock()
	defer l.mu.Unlock()
	l.syncing = syncing
	l.generation++
}

func (l *downloaderLatch) Snapshot() uint64 {
	if l == nil {
		return 0
	}
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.generation
}

func (l *downloaderLatch) ClearIfUnchanged(generation uint64) bool {
	if l == nil {
		return false
	}
	l.mu.Lock()
	defer l.mu.Unlock()
	if !l.clearIfUnchanged(generation) {
		return false
	}
	return true
}

func (l *downloaderLatch) clearIfUnchanged(generation uint64) bool {
	if l.generation != generation {
		return false
	}
	l.syncing = false
	return true
}

