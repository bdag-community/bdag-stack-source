func (m *BdagPool) AnnounceNewTransactions(txs []*types.Transaction) error {
	txds := make([]*qtypes.TxDesc, 0, len(txs))

	// Collect transactions to announce, wrapped in TxDesc
	for _, tx := range txs {
		// Wrap the transaction in a TxDesc object
		cost := tx.Cost()
		cost = cost.Sub(cost, tx.Value())
		cost = cost.Div(cost, qcommon.Precision)
		fee := cost.Int64()
		td := &qtypes.TxDesc{
			Tx:       tx,
			Added:    time.Now(),
			Height:   m.chain.CurrentBlock().Number.Int64(),
			Fee:      fee,
			FeePerKB: fee * 1000 / int64(tx.Size()),
		}
		txds = append(txds, td)
	}

	// If no transactions to announce, return early
	if len(txds) == 0 {
		return nil
	}

	if m.isSyncing() {
		for _, tx := range txs {
			_ = m.notify.RelayTransaction(tx)
		}
		go m.notify.AddRebroadcastInventory(txds)
		return nil
	}

	// Announce new transactions using the notify interface
	m.notify.AnnounceNewTransactions(txds, nil)

	// Optionally add transactions to rebroadcast inventory in a separate goroutine
	go m.notify.AddRebroadcastInventory(txds)

	return nil
}

