func (m *BdagPool) subscribe() {
	ch := make(chan *qevent.Event)
	sub := m.consensus.Events().Subscribe(ch)
	go func() {
		defer sub.Unsubscribe()
		for {
			select {
			case ev := <-ch:
				if ev.Data != nil {
					switch value := ev.Data.(type) {
					case int:
						if value == qevent.DownloaderStart {
							m.syncing.Store(true)
						} else if value == qevent.DownloaderEnd {
							m.syncing.Store(false)
							if err := m.ResetTemplate(); err != nil {
								log.Warn("BdagPool reset failed after downloader finished", "err", err)
							}
						}
					}
				}
				if ev.Ack != nil {
					ev.Ack <- struct{}{}
				}
			case <-m.quit:
				log.Info("Close BdagPool Event Subscribe")
				return
			}
		}
	}()
}

