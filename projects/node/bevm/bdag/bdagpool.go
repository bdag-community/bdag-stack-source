func (m *BdagPool) init(consensus model.Consensus, config *miner.Config, chainConfig *params.ChainConfig, engine consensus.Engine, eth Backend, mux *event.TypeMux) error {
	log.Info(fmt.Sprintf("bdag pool init..."))

	m.consensus = consensus
	m.config = config
	m.chainConfig = chainConfig
	m.engine = engine
	m.eth = eth
	m.mux = mux
	m.chain = eth.BlockChain()
	m.installGovernanceAdmissibilityHook()
	for _, sp := range eth.TxPool().Subpools() {
		ltp, ok := sp.(*legacypool.LegacyPool)
		if ok {
			m.ethTxPool = ltp
			break
		}
	}
	m.txsCh = make(chan core.NewTxsEvent, txChanSize)
	m.chainHeadCh = make(chan core.ChainHeadEvent, chainHeadChanSize)
	m.quit = make(chan struct{})
	m.resetTemplate = make(chan *resetTemplateMsg)
	m.chainHeadSub = eth.BlockChain().SubscribeChainHeadEvent(m.chainHeadCh)
	m.txsSub = m.eth.TxPool().SubscribeTransactions(m.txsCh, true)
	return nil
}

func (m *BdagPool) Start() {
	if m.isRunning() {
		log.Info("bdag pool was started")
		return
	}

	atomic.StoreInt32(&m.running, 1)

	m.quit = make(chan struct{})
	m.wg.Add(1)
	go m.handler()
	m.subscribe()

	if m.deferInitialTemplateUpdate() {
		log.Info("BdagPool initial template update deferred while node is syncing")
		return
	}

	if err := m.updateTemplate(nil, time.Now().Unix(), false, false); err != nil {
		log.Warn("BdagPool initial template update failed", "err", err)
	}
}

func (m *BdagPool) Close() {

}

func (m *BdagPool) Stop() {
	if !m.isRunning() {
		log.Info("bdag pool was stopped")
		return
	}
	atomic.StoreInt32(&m.running, 0)

	log.Info(fmt.Sprintf("bdag pool stopping"))
	if m.current != nil {
		m.current.discard()
	}
	close(m.quit)
	m.wg.Wait()

	log.Info(fmt.Sprintf("bdag pool stopped"))
}

func (m *BdagPool) UnsubscribeForRecovery() {
	if m == nil {
		return
	}
	if m.txsSub != nil {
		m.txsSub.Unsubscribe()
	}
	if m.chainHeadSub != nil {
		m.chainHeadSub.Unsubscribe()
	}
}

func (m *BdagPool) isRunning() bool {
	return atomic.LoadInt32(&m.running) == 1
}

func (m *BdagPool) initialSyncing() bool {
	if m == nil {
		return false
	}
	if m.evmImportBehindMainTip() {
		return true
	}
	if m.evmBehindPeerTarget() {
		return true
	}
	if m.evmSyncProgressActive() {
		return true
	}
	if m.consensus == nil || m.consensus.BlockChain() == nil {
		return false
	}
	chain, ok := m.consensus.BlockChain().(chainCurrentChecker)
	if !ok {
		return false
	}
	return !chain.IsCurrent()
}

func (m *BdagPool) deferInitialTemplateUpdate() bool {
	// initialSyncing is derived from live chain state. Do not copy it into the
	// downloader event latch: a native or EVM catch-up has no guaranteed
	// matching DownloaderEnd event and would otherwise suppress templates until
	// restart after the live heads become canonical again.
	return m.initialSyncing()
}

func (m *BdagPool) IsSyncing() bool {
	if m == nil {
		return false
	}
	return m.isSyncing()
}

// CanonicalMiningTemplateReady reports whether the live execution head exactly
// matches the atomically published native-to-EVM commitment. It deliberately
// ignores only the downloader event latch; live import, peer-target, and sync
// progress checks remain authoritative.
func (m *BdagPool) CanonicalMiningTemplateReady() bool {
	if m == nil || m.chain == nil || m.consensus == nil || m.consensus.BlockChain() == nil {
		return false
	}
	if provider, ok := m.consensus.BlockChain().(model.LocalEVMRecoveryProvider); ok {
		if held, _ := provider.LocalEVMRecoveryStatus(); held {
			return false
		}
	}
	provider, ok := m.consensus.BlockChain().(committedEVMHeadProvider)
	if !ok {
		return false
	}
	hash, number, root, valid, known := provider.CommittedEVMHead()
	return canonicalMiningTemplateReady(
		m.chain.CurrentBlock(), hash, number, root, valid, known,
		m.evmImportBehindMainTip(), m.evmBehindPeerTarget(), m.evmSyncProgressActive(),
	)
}

func committedEVMHeadMatches(current *types.Header, hash common.Hash, number uint64, root common.Hash, valid, known bool) bool {
	return known && valid && current != nil && current.Number != nil &&
		current.Number.Uint64() == number && current.Hash() == hash && current.Root == root
}

func canonicalMiningTemplateReady(
	current *types.Header,
	hash common.Hash,
	number uint64,
	root common.Hash,
	valid bool,
	known bool,
	evmImportBehind bool,
	evmBehindPeer bool,
	evmSyncProgressActive bool,
) bool {
	return committedEVMHeadMatches(current, hash, number, root, valid, known) &&
		!evmImportBehind && !evmBehindPeer && !evmSyncProgressActive
}

func (m *BdagPool) isSyncing() bool {
	if m == nil {
		return false
	}
	return m.syncing.Load() || m.evmImportBehindMainTip() || m.evmBehindPeerTarget() || m.evmSyncProgressActive()
}

func (m *BdagPool) SetPeerEVMTargetProvider(provider func() uint64) {
	if m == nil {
		return
	}
	m.peerEVMTarget = provider
}

func (m *BdagPool) evmImportBehindMainTip() bool {
	if m == nil || m.chain == nil || m.consensus == nil || m.consensus.BlockChain() == nil {
		return false
	}
	return evmImportBehindMainTip(m.chain.CurrentBlock(), m.consensus.BlockChain().GetMainChainTip())
}

func evmImportBehindMainTip(currentEVM *types.Header, mainTip model.Block) bool {
	if mainTip == nil || mainTip.GetState() == nil {
		return false
	}
	mainTipEVM := mainTip.GetState().GetEVMNumber()
	if mainTipEVM == 0 {
		return false
	}
	if currentEVM == nil || currentEVM.Number == nil {
		return true
	}
	return currentEVM.Number.Uint64() < mainTipEVM
}

func (m *BdagPool) evmBehindPeerTarget() bool {
	if m == nil || m.chain == nil || m.peerEVMTarget == nil {
		return false
	}
	target := m.peerEVMTarget()
	if nativeTarget := m.nativeMainTipEVM(); nativeTarget > 0 && target > nativeTarget {
		target = nativeTarget
	}
	return evmBehindPeerTarget(m.chain.CurrentBlock(), target)
}

func evmBehindPeerTarget(currentEVM *types.Header, target uint64) bool {
	if target == 0 {
		return false
	}
	if currentEVM == nil || currentEVM.Number == nil {
		return true
	}
	return currentEVM.Number.Uint64() < target
}

func (m *BdagPool) evmSyncProgressActive() bool {
	if m == nil || m.eth == nil {
		return false
	}
	if provider, ok := m.eth.(syncProgressProvider); ok {
		return m.evmSyncProgressBlocksNative(provider.SyncProgress())
	}
	provider, ok := m.eth.(syncDownloaderProvider)
	if !ok {
		return false
	}
	downloader := provider.Downloader()
	if downloader == nil {
		return false
	}
	return m.evmSyncProgressBlocksNative(downloader.Progress())
}

func (m *BdagPool) evmSyncProgressBlocksNative(progress ethereum.SyncProgress) bool {
	if progress.Done() {
		return false
	}
	nativeTarget := m.nativeMainTipEVM()
	if nativeTarget == 0 {
		return true
	}
	return progress.CurrentBlock < nativeTarget
}

func (m *BdagPool) nativeMainTipEVM() uint64 {
	if m == nil || m.consensus == nil || m.consensus.BlockChain() == nil {
		return 0
	}
	mainTip := m.consensus.BlockChain().GetMainChainTip()
	if mainTip == nil || mainTip.GetState() == nil {
		return 0
	}
	return mainTip.GetState().GetEVMNumber()
}

func (m *BdagPool) handler() {
	defer m.txsSub.Unsubscribe()
	defer m.chainHeadSub.Unsubscribe()
	defer m.wg.Done()
	defer func() {
		if m.current != nil {
			m.current.discard()
		}
	}()
	for {
		select {
		case ev := <-m.txsCh:

			if m.shouldProcessTxEventForTemplate() {
				if gp := m.current.gasPool; gp != nil && gp.Gas() < params.TxGas {
					continue
				}

				txs := make(map[common.Address][]*txpool.LazyTransaction, len(ev.Txs))
				for _, tx := range ev.Txs {
					acc, _ := types.Sender(m.current.signer, tx)
					txs[acc] = append(txs[acc], &txpool.LazyTransaction{
						Hash:      tx.Hash(),
						Tx:        tx.WithoutBlobTxSidecar(),
						Time:      tx.Time(),
						GasFeeCap: uint256.MustFromBig(tx.GasFeeCap()),
						GasTipCap: uint256.MustFromBig(tx.GasTipCap()),
					})
				}
				txset := miner.NewTransactionsByPriceAndNonce(m.current.signer, txs, m.current.header.BaseFee)
				tcount := m.current.tcount
				m.commitTransactions(m.current, txset, nil)
				if tcount != m.current.tcount {
					m.updateSnapshot(m.current)
				}
			}
			// Always announce txs from the txpool event (includes queued->pending promotions).
			m.AnnounceNewTransactions(ev.Txs)

		// System stopped
		case <-m.quit:
			return
		case <-m.txsSub.Err():
			return
		case ev := <-m.chainHeadCh:
			now := time.Now()
			interrupt, shouldUpdate := m.prepareChainHeadTemplateUpdate(ev.Block, now)
			if !shouldUpdate {
				continue
			}
			if err := m.updateTemplate(interrupt, now.Unix(), false, false); err != nil {
				if errors.Is(err, errBdagPoolSyncing) {
					log.Debug("BdagPool template update skipped while node is syncing")
				} else {
					log.Warn("BdagPool template update failed after chain head", "err", err)
				}
			}
		case <-m.chainHeadSub.Err():
			return
		case msg := <-m.resetTemplate:
			if m.interrupt != nil {
				m.interrupt.Store(commitInterruptResubmit)
			}
			m.interrupt = new(atomic.Int32)
			msg.reply <- m.updateTemplateWithGeneration(m.interrupt, time.Now().Unix(), true, msg.allowWhileSyncing, msg.syncGeneration, msg.guardSyncState)
		}
	}
}

func (m *BdagPool) shouldProcessTxEventForTemplate() bool {
	if m == nil || m.current == nil {
		return false
	}
	return !m.isSyncing()
}

func (m *BdagPool) prepareChainHeadTemplateUpdate(block *types.Block, now time.Time) (*atomic.Int32, bool) {
	if m.interrupt != nil {
		m.interrupt.Store(commitInterruptNewHead)
	}
	if !m.shouldUpdateTemplateAfterChainHead(block, now) {
		m.interrupt = nil
		return nil, false
	}
	m.interrupt = new(atomic.Int32)
	return m.interrupt, true
}

func (m *BdagPool) shouldUpdateTemplateAfterChainHead(block *types.Block, now time.Time) bool {
	if m.isSyncing() {
		return false
	}
	if block == nil {
		return true
	}
	if now.IsZero() {
		now = time.Now()
	}
	headTime := time.Unix(int64(block.Time()), 0)
	return now.Sub(headTime) <= chainHeadTemplateRefreshMaxAge
}

func (m *BdagPool) ValidateTxDirect(tx *types.Transaction, checkState bool) error {
	// Reject transactions over defined size to prevent DOS attacks
	if tx.Size() > txMaxSize {
		return txpool.ErrOversizedData
	}
	if tx.Value().Sign() < 0 {
		return txpool.ErrNegativeValue
	}
	if tx.GasFeeCap().BitLen() > 256 {
		return core.ErrFeeCapVeryHigh
	}
	if tx.GasTipCap().BitLen() > 256 {
		return core.ErrTipVeryHigh
	}
	if tx.GasFeeCapIntCmp(tx.GasTipCap()) < 0 {
		return core.ErrTipAboveFeeCap
	}
	head := m.eth.BlockChain().CurrentBlock()
	if head == nil || head.Number == nil {
		return fmt.Errorf("EVM head unavailable for transaction signing domain")
	}
	from, err := types.Sender(types.MakeSigner(m.eth.BlockChain().Config(), new(big.Int).Add(head.Number, big.NewInt(1)), head.Time), tx)
	if err != nil {
		return txpool.ErrInvalidSender
	}
	if checkState {
		currentState, err := m.eth.BlockChain().State()
		if err != nil {
			return err
		}
		currentNonce := currentState.GetNonce(from)
		if currentNonce > tx.Nonce() {
			log.Debug("Nonce too low in validateTxDirect", "from", from, "nonce", tx.Nonce(), "currentNonce", currentNonce)
			return core.ErrNonceTooLow
		}
		if currentNonce < tx.Nonce() {
			return fmt.Errorf("nonce too high: got %d, expected %d", tx.Nonce(), currentNonce)
		}
		if currentState.GetBalance(from).ToBig().Cmp(tx.Cost()) < 0 {
			return core.ErrInsufficientFunds
		}
		if err := TemplateGovernanceAdmissibility().CheckTransaction(currentState, from, tx.To(), tx.Value()); err != nil {
			return err
		}
	}
	intrGas, err := core.IntrinsicGas(tx.Data(), tx.AccessList(), tx.To() == nil, true, true, false)
	if err != nil {
		return err
	}
	if tx.Gas() < intrGas {
		return core.ErrIntrinsicGas
	}
	return nil
}

func (m *BdagPool) GetSnapshot() *state.StateDB {
	return m.snapshotState
}

func (m *BdagPool) updateSnapshot(env *environment) {
	m.snapshotMu.Lock()
	defer m.snapshotMu.Unlock()

	m.snapshotBlock = types.NewBlock(
		env.header,
		&types.Body{Transactions: env.txs},
		env.receipts,
		trie.NewStackTrie(nil),
	)

	m.snapshotReceipts = qcommon.CopyReceipts(env.receipts)
	m.snapshotState = env.state.Copy()

	//
	log.Info("update BdagPool snapshot", "size", len(m.snapshotBlock.Transactions()))
}

func (m *BdagPool) commitTransaction(env *environment, tx *types.Transaction) ([]*types.Log, error) {
	if tx.Type() == types.BlobTxType {
		return m.commitBlobTransaction(env, tx)
	}

	receipt, err := m.applyTransaction(env, tx)
	if err != nil {
		return nil, err
	}
	env.txs = append(env.txs, tx)
	env.receipts = append(env.receipts, receipt)
	return receipt.Logs, nil
}

func (m *BdagPool) commitBlobTransaction(env *environment, tx *types.Transaction) ([]*types.Log, error) {
	sc := tx.BlobTxSidecar()
	if sc == nil {
		panic("blob transaction without blobs in miner")
	}
	// Checking against blob gas limit: It's kind of ugly to perform this check here, but there
	// isn't really a better place right now. The blob gas limit is checked at block validation time
	// and not during execution. This means core.ApplyTransaction will not return an error if the
	// tx has too many blobs. So we have to explicitly check it here.
	if (env.blobs+len(sc.Blobs))*params.BlobTxBlobGasPerBlob > params.MaxBlobGasPerBlock {
		return nil, errors.New("max data blobs reached")
	}

	receipt, err := m.applyTransaction(env, tx)
	if err != nil {
		return nil, err
	}
	env.txs = append(env.txs, tx.WithoutBlobTxSidecar())
	env.receipts = append(env.receipts, receipt)
	env.sidecars = append(env.sidecars, sc)
	env.blobs += len(sc.Blobs)
	*env.header.BlobGasUsed += receipt.BlobGasUsed
	return receipt.Logs, nil
}

// applyTransaction runs the transaction. If execution fails, state and gas pool are reverted.
func (m *BdagPool) applyTransaction(env *environment, tx *types.Transaction) (*types.Receipt, error) {
	var (
		snap = env.state.Snapshot()
		gp   = env.gasPool.Gas()
	)
	vmConfig := TemplateGovernanceAdmissibility().applyToVMConfig(*m.chain.GetVMConfig())
	receipt, err := core.ApplyTransaction(m.chainConfig, m.chain, &env.coinbase, env.gasPool, env.state, env.header, tx, &env.header.GasUsed, vmConfig)
	if err != nil {
		env.state.RevertToSnapshot(snap)
		env.gasPool.SetGas(gp)
	}
	return receipt, err
}

func (m *BdagPool) commitTransactions(env *environment, txs miner.TransactionsByPriceAndNonce, interrupt *atomic.Int32) error {
	gasLimit := env.header.GasLimit
	if env.gasPool == nil {
		env.gasPool = new(core.GasPool).AddGas(gasLimit)
	}
	var coalescedLogs []*types.Log

	// Best-effort mempool policy: once a governance upgrade is active, skip
	// ineligible transactions when building local block templates so this miner
	// never produces a block that consensus would reject. The authoritative
	// gate uses ConsensusGovernanceAdmissibilityAtLayer during block validation.
	admissibility := TemplateGovernanceAdmissibility()

	for {
		// Check interruption signal and abort building if it's fired.
		if interrupt != nil {
			if signal := interrupt.Load(); signal != commitInterruptNone {
				return signalToErr(signal)
			}
		}
		if env.gasPool.Gas() < params.TxGas {
			log.Trace("Not enough gas for further transactions", "have", env.gasPool, "want", params.TxGas)
			break
		}
		ltx, _ := txs.Peek()
		if ltx == nil {
			break
		}
		tx := ltx.Resolve()
		if tx == nil {
			log.Warn("Ignoring evicted transaction")

			txs.Pop()
			continue
		}
		from, _ := types.Sender(env.signer, tx)
		if tx.Protected() && !m.chainConfig.IsEIP155(env.header.Number) {
			log.Trace("Ignoring reply protected transaction", "hash", tx.Hash(), "eip155", m.chainConfig.EIP155Block)

			txs.Pop()
			continue
		}
		if err := admissibility.CheckTransaction(env.state, from, tx.To(), tx.Value()); err != nil {
			log.Debug("Skipping governance-inadmissible transaction in template", "hash", tx.Hash(), "from", from.Hex(), "err", err)
			txs.Pop()
			continue
		}
		env.state.SetTxContext(tx.Hash(), env.tcount)
		logs, err := m.commitTransaction(env, tx)
		switch {
		case errors.Is(err, core.ErrNonceTooLow):
			// New head notification data race between the transaction pool and miner, shift
			log.Trace("Skipping transaction with low nonce", "sender", from, "nonce", tx.Nonce())
			txs.Shift()

		case errors.Is(err, nil):
			// Everything ok, collect the logs and shift in the next transaction from the same account
			coalescedLogs = append(coalescedLogs, logs...)
			env.tcount++
			txs.Shift()

		default:
			// Transaction is regarded as invalid, drop all consecutive transactions from
			// the same sender because of `nonce-too-high` clause.
			log.Debug("Transaction failed, account skipped", "hash", tx.Hash(), "err", err)
			txs.Pop()
		}
	}
	if len(coalescedLogs) > 0 {
		cpy := make([]*types.Log, len(coalescedLogs))
		for i, l := range coalescedLogs {
			cpy[i] = new(types.Log)
			*cpy[i] = *l
		}
		m.pendingLogsFeed.Send(cpy)
	}
	return nil
}

func (m *BdagPool) prepareEnv(genParams *generateParams) (*environment, error) {
	parent := m.chain.CurrentBlock()
	if genParams.parentHash != (common.Hash{}) {
		block := m.chain.GetBlockByHash(genParams.parentHash)
		if block == nil {
			return nil, fmt.Errorf("missing parent")
		}
		parent = block.Header()
	}
	// Map native/template time onto the EVM ledger clock (see blocktime.go).
	timestamp := ResolveEVMBlockTimestamp(parent.Time, int64(genParams.timestamp), m.chainConfig.ChainID)
	if genParams.forceTime && timestamp != genParams.timestamp {
		return nil, fmt.Errorf("invalid timestamp, parent %d given %d resolved %d", parent.Time, genParams.timestamp, timestamp)
	}
	gaslimit := core.CalcGasLimit(parent.GasLimit, m.config.GasCeil)
	if mparams.IsMainnetChainID(m.chainConfig.ChainID) {
		gaslimit = mparams.MainnetFixedGasLimit
	}

	num := big.NewInt(0)
	num.Set(parent.Number)
	header := &types.Header{
		ParentHash: parent.Hash(),
		Number:     num.Add(num, common.Big1),
		GasLimit:   gaslimit,
		Time:       timestamp,
		Coinbase:   m.config.Etherbase,
		Difficulty: common.Big1,
	}
	// Set the extra field.
	if len(m.config.ExtraData) != 0 {
		header.Extra = m.config.ExtraData
	}
	if m.chainConfig.BdagTestnetTiming != nil {
		if m.consensus == nil || m.consensus.BlockChain() == nil {
			return nil, fmt.Errorf("timing template requires native chain context")
		}
		if err := prepareTimingTemplateRewardExtra(m.chainConfig, header, m.consensus.BlockChain().GetMainChainTip()); err != nil {
			return nil, err
		}
	}
	// Set the randomness field from the beacon chain if it's available.
	if genParams.random != (common.Hash{}) {
		header.MixDigest = genParams.random
	}
	// Set baseFee and GasLimit if we are on an EIP-1559 chain
	if m.chainConfig.IsLondon(header.Number) {
		header.BaseFee = eip1559.CalcBaseFee(m.chainConfig, parent)
		if !m.chainConfig.IsLondon(parent.Number) {
			parentGasLimit := parent.GasLimit * m.chainConfig.ElasticityMultiplier()
			header.GasLimit = core.CalcGasLimit(parentGasLimit, m.config.GasCeil)
		}
	}
	if mparams.IsMainnetChainID(m.chainConfig.ChainID) {
		header.GasLimit = mparams.MainnetFixedGasLimit
	}
	// Apply EIP-4844, EIP-4788.
	if m.chainConfig.IsCancun(header.Number, header.Time) {
		var excessBlobGas uint64
		if m.chainConfig.IsCancun(parent.Number, parent.Time) {
			excessBlobGas = eip4844.CalcExcessBlobGas(*parent.ExcessBlobGas, *parent.BlobGasUsed)
		} else {
			// For the first post-fork block, both parent.data_gas_used and parent.excess_data_gas are evaluated as 0
			excessBlobGas = eip4844.CalcExcessBlobGas(0, 0)
		}
		header.BlobGasUsed = new(uint64)
		header.ExcessBlobGas = &excessBlobGas
		header.ParentBeaconRoot = genParams.beaconRoot
	}
	if err := m.engine.Prepare(m.chain, header); err != nil {
		log.Error("Failed to prepare header for BdagPool", "err", err)
		return nil, err
	}
	env, err := m.makeEnv(parent, header, genParams.coinbase)
	if err != nil {
		log.Error("Failed to create BdagPool context", "err", err)
		return nil, err
	}
	// Keep the pending state consistent with what buildBlock/Process will produce.
	bdagconsensus.ApplyPreBlockStateChanges(m.engine, m.chain, header, env.state)
	if header.ParentBeaconRoot != nil {
		context := core.NewEVMBlockContext(header, m.chain, nil)
		vmenv := vm.NewEVM(context, vm.TxContext{}, env.state, m.chainConfig, vm.Config{})
		core.ProcessBeaconBlockRoot(*header.ParentBeaconRoot, vmenv, env.state)
	}
	return env, nil
}

func (m *BdagPool) makeEnv(parent *types.Header, header *types.Header, coinbase common.Address) (*environment, error) {
	state, err := m.chain.StateAt(parent.Root)
	if err != nil {
		return nil, err
	}
	state.StartPrefetcher("BdagPool", nil)

	env := &environment{
		signer:   types.MakeSigner(m.chainConfig, header.Number, header.Time),
		state:    state,
		coinbase: coinbase,
		header:   header,
	}
	env.tcount = 0
	return env, nil
}

func (m *BdagPool) updateTemplate(interrupt *atomic.Int32, timestamp int64, force bool, allowWhileSyncing bool) error {
	return m.updateTemplateWithGeneration(interrupt, timestamp, force, allowWhileSyncing, 0, false)
}

func (m *BdagPool) updateTemplateWithGeneration(interrupt *atomic.Int32, timestamp int64, force bool, allowWhileSyncing bool, syncGeneration uint64, guardSyncState bool) error {
	updateStart := time.Now()
	defer bdagPoolTemplateUpdateDuration.UpdateSince(updateStart)

	if m.isSyncing() {
		if !allowWhileSyncing || !m.CanonicalMiningTemplateReady() {
			return errBdagPoolSyncing
		}
	}
	preBlock := m.PendingBlock()
	if preBlock != nil && !force {
		if preBlock.ParentHash() == m.chain.CurrentBlock().Hash() {
			log.Debug("BdagPool block template no update required")
			return nil
		}
	}
	log.Debug("BdagPool update block template")
	m.mu.Lock()
	defer m.mu.Unlock()

	start := time.Now()

	env, err := m.prepareEnv(&generateParams{
		timestamp: uint64(timestamp),
		coinbase:  m.config.Etherbase,
	})
	if err != nil {
		return fmt.Errorf("prepare bdag pool template: %w", err)
	}
	// Fill pending transactions from the txpool into the block.
	err = m.fillTransactions(interrupt, env)
	switch {
	case errors.Is(err, errBlockInterruptedByNewHead):
		// If the block building is interrupted by newhead event, discard it
		// totally. Committing the interrupted block introduces unnecessary
		// delay, and possibly causes miner to mine on the previous head,
		// which could result in higher uncle rate.
		env.discard()
		return err
	case err != nil:
		env.discard()
		return fmt.Errorf("fill bdag pool template transactions: %w", err)
	}
	// Submit the generated block for consensus sealing.

	commitStart := time.Now()
	if err := m.commit(env, !guardSyncState, start); err != nil {
		bdagPoolTemplateCommitDuration.UpdateSince(commitStart)
		env.discard()
		return fmt.Errorf("commit bdag pool template: %w", err)
	}
	bdagPoolTemplateCommitDuration.UpdateSince(commitStart)
	if guardSyncState {
		if err := m.finalizeCanonicalTemplate(syncGeneration, m.CanonicalMiningTemplateReady, func() {
			m.updateSnapshot(env)
			m.installTemplateEnvironment(env)
		}); err != nil {
			env.discard()
			return err
		}
		return nil
	}
	if allowWhileSyncing && !m.CanonicalMiningTemplateReady() {
		env.discard()
		return errBdagPoolSyncing
	}

	// Swap out the old work with the new one, terminating any leftover
	// prefetcher processes in the mean time and starting a new one.
	m.installTemplateEnvironment(env)
	return nil
}

// finalizeCanonicalTemplate makes the generation check, latch clear, and
// candidate installation one atomic decision. Downloader events block on the
// latch mutex, so a start observed before this boundary advances the
// generation and prevents install; a start after it leaves the latch active.
func (m *BdagPool) finalizeCanonicalTemplate(syncGeneration uint64, canonicalReady func() bool, install func()) error {
	if m.beforeCanonicalTemplateBoundary != nil {
		m.beforeCanonicalTemplateBoundary()
	}
	m.syncing.mu.Lock()
	defer m.syncing.mu.Unlock()
	if !canonicalReady() || !m.syncing.clearIfUnchanged(syncGeneration) {
		return errBdagPoolSyncing
	}
	install()
	return nil
}

func (m *BdagPool) installTemplateEnvironment(env *environment) {
	if m.current != nil {
		m.current.discard()
	}
	m.current = env
}

func (m *BdagPool) fillTransactions(interrupt *atomic.Int32, env *environment) error {
	// Retrieve the pending transactions pre-filtered by the 1559/4844 dynamic fees
	filter := txpool.PendingFilter{
		MinTip: uint256.MustFromBig(m.config.GasPrice),
	}
	if env.header.BaseFee != nil {
		filter.BaseFee = uint256.MustFromBig(env.header.BaseFee)
	}
	if env.header.ExcessBlobGas != nil {
		filter.BlobFee = uint256.MustFromBig(eip4844.CalcBlobFee(*env.header.ExcessBlobGas))
	}
	filter.OnlyPlainTxs, filter.OnlyBlobTxs = true, false

	pending := m.eth.TxPool().Pending(filter)

	// Split the pending transactions into locals and remotes.
	localTxs, remoteTxs := make(map[common.Address][]*txpool.LazyTransaction), pending
	for _, account := range m.eth.TxPool().Locals() {
		if txs := remoteTxs[account]; len(txs) > 0 {
			delete(remoteTxs, account)
			localTxs[account] = txs
		}
	}

	// Fill the block with all available pending transactions.
	if len(localTxs) > 0 {
		txs := miner.NewTransactionsByPriceAndNonce(env.signer, localTxs, env.header.BaseFee)
		if err := m.commitTransactions(env, txs, interrupt); err != nil {
			return err
		}
	}
	if len(remoteTxs) > 0 {
		txs := miner.NewTransactionsByPriceAndNonce(env.signer, remoteTxs, env.header.BaseFee)
		if err := m.commitTransactions(env, txs, interrupt); err != nil {
			return err
		}
	}
	return nil
}

