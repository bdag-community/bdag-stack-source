// Single source of truth for the staking ABI.
//   npx hardhat run scripts/abi/export-abi.js            -> abi/StakingContract.json
//   npx hardhat run scripts/abi/export-abi.js -- --sync  -> also rewrites the backend + frontend ABI files
// Exports the V2 ABI (a strict superset of V1, enforced by test/StorageLayout.test.js), so both apps
// can ship it before the switchover; version()/v2ActivatedAt() simply revert on V1.
const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");
const hre = require("hardhat");

const CONTRACT = "contracts/staking/StakingPoolV2.sol:StakingContractV2";
const ROOT = path.join(__dirname, "..", "..");
const BACKEND = process.env.BACKEND_DIR || path.join(ROOT, "..", "staking-backend-community");
const FRONTEND = process.env.FRONTEND_DIR || path.join(ROOT, "..", "staking-frontend-community");

function gitSha() { try { return execSync("git rev-parse --short HEAD", { cwd: ROOT }).toString().trim(); } catch { return "unknown"; } }

async function main() {
    const sync = process.argv.includes("--sync") || process.env.ABI_SYNC === "1";
    const artifact = await hre.artifacts.readArtifact(CONTRACT);
    const abi = artifact.abi;
    fs.mkdirSync(path.join(ROOT, "abi"), { recursive: true });
    const jsonPath = path.join(ROOT, "abi", "StakingContract.json");
    fs.writeFileSync(jsonPath, JSON.stringify(abi, null, 2) + "\n");
    console.log(`wrote ${path.relative(ROOT, jsonPath)} (${abi.length} entries)`);
    if (!sync) return;

    const header = `// GENERATED by Contract-Staking scripts/abi/export-abi.js from ${CONTRACT} @ ${gitSha()}.\n// Do not edit by hand. Regenerate with: npm run abi:sync (in Contract-Staking).\n`;
    const targets = [
        [path.join(BACKEND, "src", "contract", "abi.contract.ts"), `${header}export const abi = ${JSON.stringify(abi, null, 2)};\n`],
        [path.join(FRONTEND, "src", "contract", "abi.ts"), `${header}export const abi = ${JSON.stringify(abi, null, 2)} as const;\n`],
    ];
    for (const [file, content] of targets) {
        if (!fs.existsSync(path.dirname(file))) { console.warn(`skip (missing dir): ${file}`); continue; }
        fs.writeFileSync(file, content);
        console.log(`synced ${file}`);
    }
}

main().catch((e) => { console.error(e); process.exit(1); });
